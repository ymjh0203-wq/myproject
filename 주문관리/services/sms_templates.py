def render_template(template_key: str, order: dict) -> str:
    """
    템플릿 문구의 {상품명}/{고객명}/{주문번호}/{전화번호}를 실제 주문 정보로
    채운 최종 문자 내용을 돌려줍니다.
    """
    shipping = order["shipping"] or {}
    items = order["items"]
    product_name = (items[0]["product_name"] if items else "") or ""

    values = {
        "상품명": product_name[:5],
        "고객명": shipping.get("receiver_name") or "",
        "주문번호": order["market_order_id"] or "",
        "전화번호": shipping.get("customs_phone") or shipping.get("receiver_phone_raw") or "",
    }

    text = TEMPLATES[template_key]["text"]
    for key, value in values.items():
        text = text.replace("{" + key + "}", value)
    return text
