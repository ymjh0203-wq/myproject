# 아직 만드는 중입니다. 합의된 상품명 생성 알고리즘의 자리만 잡아둡니다.
#   1) 상대 상품명에서 키워드 후보 자동추출 → 메인/서브 확정(반자동)
#   2) 메인 키워드로 네이버 자동완성/연관검색어 수집 → 키워드 풀
#   3) 메인+서브 고정 + 풀 키워드를 상품마다 다르게 조합 → 상품명 3개
#   4) 옵션명(중국어) → 한국어 정리/번역
# ============================================================

import streamlit as st

st.title("상품 가공")
st.caption("수집한 상품을 상품명·옵션 가공해 등록용으로 다듬습니다.")

st.info("이 단계는 다음 순서로 만들 예정입니다.", icon=":material/build:")

st.markdown(
    """
1. **키워드 후보 추출** — 기준(상대) 상품명을 쪼개 후보 키워드로 표시
2. **메인/서브 확정** — 후보 중 메인 1개 + 서브 몇 개를 직접 선택 (반자동)
3. **키워드 풀 수집** — 메인 키워드로 네이버 자동완성/연관검색어를 모아 풀 구성
4. **상품명 3개 생성** — 메인+서브 고정, 뒤에 풀 키워드를 상품마다 다르게 조합
   (중복 제거, 스마트스토어 50자 제한)
5. **옵션명 가공** — 중국어 옵션 → 한국어 정리/번역
    """
)

st.warning(
    "네이버 자동완성/연관검색어도 크롤링이라 차단될 수 있고, 상대 상품명·브랜드명 "
    "그대로 도용은 상표/어뷰징 위험이 있어 '메인 키워드 재사용 + 조합 변형'까지가 안전선입니다.",
    icon=":material/gpp_maybe:",
)
